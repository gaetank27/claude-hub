// Package imgsafe vets the image files the assistant (or any tool driven by a
// model reading untrusted content) wants to send out of the Hub. The model may be
// manipulated by an injection, so a path it gives is never trusted: it must
// resolve (symlinks followed) inside an allow-listed directory, avoid anything
// that looks like a secret, be a REAL raster image by its magic bytes (no SVG, no
// active format), stay under a size and pixel budget, and is decoded and
// re-encoded (which also strips EXIF/GPS and any appended payload).
package imgsafe

import (
	"bytes"
	"errors"
	"fmt"
	"image"
	"image/color"
	"image/gif"
	"image/jpeg"
	"image/png"
	"io"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"

	xdraw "golang.org/x/image/draw"
	"golang.org/x/image/webp"
)

const (
	DefaultMaxBytes  = 10 << 20   // source file
	DefaultMaxPixels = 50_000_000 // decoded size (decompression-bomb guard)
	DefaultMaxDim    = 2048       // longest side after resizing
	maxOutBytes      = 8 << 20    // a PNG above this is sent as JPEG instead
	DefaultPerHour   = 10
)

// Error is a refusal worded for the model (it relays it to the user). Code is
// stable: path | denied | type | too_large | empty | decode | rate.
type Error struct{ Code, Message string }

func (e *Error) Error() string { return e.Message }

func refuse(code, format string, a ...any) *Error {
	return &Error{code, fmt.Sprintf(format, a...)}
}

// Policy is what may be read.
type Policy struct {
	// Roots are the directories an image may live in (after symlink resolution).
	Roots []string
	// Deny are directories refused even when inside a root (data dir, ~/.ssh…).
	Deny      []string
	MaxBytes  int64
	MaxPixels int
	MaxDim    int
}

// DefaultPolicy allows the projects directory (files generated by sessions, the
// received attachments) and the given extra dirs (e.g. a dedicated /tmp dir),
// and explicitly denies the sensitive places of the host.
func DefaultPolicy(projectsRoot, home, dataDir string, extra ...string) *Policy {
	p := &Policy{MaxBytes: DefaultMaxBytes, MaxPixels: DefaultMaxPixels, MaxDim: DefaultMaxDim}
	for _, r := range append([]string{projectsRoot}, extra...) {
		if r = realDir(r); r != "" {
			p.Roots = append(p.Roots, r)
		}
	}
	deny := []string{"/etc", "/proc", "/sys", "/dev", "/root", "/boot", "/var", dataDir}
	if home != "" {
		for _, d := range []string{".ssh", ".config", ".local", ".claude", ".gnupg", ".aws", ".kube", ".docker", ".password-store"} {
			deny = append(deny, filepath.Join(home, d))
		}
	}
	for _, d := range deny {
		if d == "" {
			continue
		}
		p.Deny = append(p.Deny, filepath.Clean(d))
		if r := realDir(d); r != "" {
			p.Deny = append(p.Deny, r)
		}
	}
	return p
}

func realDir(d string) string {
	if d == "" {
		return ""
	}
	r, err := filepath.EvalSymlinks(d)
	if err != nil {
		return ""
	}
	r, _ = filepath.Abs(r)
	return r
}

func within(path, dir string) bool {
	rel, err := filepath.Rel(dir, path)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

var (
	secretWords = []string{"secret", "token", "password", "passwd", "credential", "private", "id_rsa", "id_ed25519", "id_ecdsa",
		"apikey", "api_key", "api-key", "keystore", "wallet", "vault", "loopback", "authorized_keys", "known_hosts", "htpasswd", "shadow"}
	secretExts = []string{".env", ".pem", ".key", ".crt", ".cer", ".p12", ".pfx", ".kdbx", ".ovpn", ".db", ".sqlite", ".sqlite3", ".sql",
		".yaml", ".yml", ".json", ".toml", ".ini", ".conf", ".cfg", ".log"}
)

// sensitiveName reports whether one path component looks like a secret.
func sensitiveName(name string) bool {
	l := strings.ToLower(name)
	if strings.HasPrefix(l, ".") {
		return true // hidden files and directories (.ssh, .env, .git…)
	}
	for _, w := range secretWords {
		if strings.Contains(l, w) {
			return true
		}
	}
	for _, e := range secretExts {
		if strings.HasSuffix(l, e) {
			return true
		}
	}
	return false
}

// Check resolves path and applies the allow/deny rules; it returns the real path.
func (p *Policy) Check(path string) (string, error) {
	if strings.TrimSpace(path) == "" || strings.ContainsRune(path, 0) {
		return "", refuse("path", "chemin vide ou invalide")
	}
	if !filepath.IsAbs(path) {
		return "", refuse("path", "le chemin doit être absolu")
	}
	clean := filepath.Clean(path)
	real, err := filepath.EvalSymlinks(clean)
	if err != nil {
		return "", refuse("path", "fichier introuvable : %s", clean)
	}
	real, _ = filepath.Abs(real)
	var root string
	for _, r := range p.Roots {
		if within(real, r) {
			root = r
			break
		}
	}
	if root == "" {
		return "", refuse("denied", "chemin refusé : en dehors des dossiers autorisés (%s)", strings.Join(p.Roots, ", "))
	}
	for _, d := range p.Deny {
		if within(real, d) || within(clean, d) {
			return "", refuse("denied", "chemin refusé : dossier sensible")
		}
	}
	// Every component below the root, on the resolved path and on the path as
	// given (a clean-looking symlink must not hide a secret's name, nor the
	// reverse).
	checks := [][2]string{{real, root}}
	if r := firstRoot(p.Roots, clean); r != "" {
		checks = append(checks, [2]string{clean, r})
	}
	for _, c := range checks {
		rel, _ := filepath.Rel(c[1], c[0])
		for _, part := range strings.Split(rel, string(filepath.Separator)) {
			if part != "" && part != "." && sensitiveName(part) {
				return "", refuse("denied", "chemin refusé : fichier ou dossier sensible ou caché (%s)", part)
			}
		}
	}
	return real, nil
}

func firstRoot(roots []string, p string) string {
	for _, r := range roots {
		if within(p, r) {
			return r
		}
	}
	return ""
}

// Image is a vetted, re-encoded image ready to be stored and sent.
type Image struct {
	Data          []byte
	Mime          string // image/png | image/jpeg
	Ext           string // png | jpg
	Width, Height int
	SrcPath       string // resolved source path (for the audit log)
	SrcSize       int64
	Note          string // e.g. "GIF animé : première image"
}

// Prepare vets path against the policy and returns the re-encoded image.
func (p *Policy) Prepare(path string) (*Image, error) {
	real, err := p.Check(path)
	if err != nil {
		return nil, err
	}
	f, err := os.Open(real)
	if err != nil {
		return nil, refuse("path", "fichier illisible")
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil || !st.Mode().IsRegular() {
		return nil, refuse("path", "ce n'est pas un fichier ordinaire")
	}
	if st.Size() == 0 {
		return nil, refuse("empty", "fichier vide")
	}
	max := p.MaxBytes
	if max <= 0 {
		max = DefaultMaxBytes
	}
	if st.Size() > max {
		return nil, refuse("too_large", "image trop volumineuse (%.1f Mo) : la limite est de %d Mo", float64(st.Size())/(1<<20), max>>20)
	}
	data, err := io.ReadAll(io.LimitReader(f, max+1))
	if err != nil || int64(len(data)) > max {
		return nil, refuse("too_large", "image trop volumineuse : la limite est de %d Mo", max>>20)
	}
	img, err := p.encode(data)
	if err != nil {
		return nil, err
	}
	img.SrcPath, img.SrcSize = real, int64(len(data))
	return img, nil
}

// PrepareBytes vets an image received as raw bytes (no path involved): magic
// bytes, pixel budget, then decoding and re-encoding like Prepare.
func (p *Policy) PrepareBytes(data []byte) (*Image, error) {
	if len(data) == 0 {
		return nil, refuse("empty", "image vide")
	}
	img, err := p.encode(data)
	if err != nil {
		return nil, err
	}
	img.SrcSize = int64(len(data))
	return img, nil
}

// Format sniffs the real type from the magic bytes: png | jpeg | gif | webp | "".
func Format(b []byte) string {
	switch {
	case bytes.HasPrefix(b, []byte("\x89PNG\r\n\x1a\n")):
		return "png"
	case bytes.HasPrefix(b, []byte{0xFF, 0xD8, 0xFF}):
		return "jpeg"
	case bytes.HasPrefix(b, []byte("GIF87a")), bytes.HasPrefix(b, []byte("GIF89a")):
		return "gif"
	case len(b) >= 12 && bytes.HasPrefix(b, []byte("RIFF")) && bytes.Equal(b[8:12], []byte("WEBP")):
		return "webp"
	}
	return ""
}

func (p *Policy) encode(data []byte) (*Image, error) {
	format := Format(data)
	if format == "" {
		return nil, refuse("type", "format non accepté : seuls PNG, JPEG, WebP et GIF sont envoyés (pas de SVG ni de format actif)")
	}
	maxPix, maxDim := p.MaxPixels, p.MaxDim
	if maxPix <= 0 {
		maxPix = DefaultMaxPixels
	}
	if maxDim <= 0 {
		maxDim = DefaultMaxDim
	}
	var cfg image.Config
	var err error
	switch format {
	case "png":
		cfg, err = png.DecodeConfig(bytes.NewReader(data))
	case "jpeg":
		cfg, err = jpeg.DecodeConfig(bytes.NewReader(data))
	case "gif":
		cfg, err = gif.DecodeConfig(bytes.NewReader(data))
	case "webp":
		cfg, err = webp.DecodeConfig(bytes.NewReader(data))
	}
	if err != nil || cfg.Width <= 0 || cfg.Height <= 0 {
		return nil, refuse("decode", "image illisible ou corrompue")
	}
	if cfg.Width*cfg.Height > maxPix {
		return nil, refuse("too_large", "image trop grande (%d×%d pixels)", cfg.Width, cfg.Height)
	}
	var im image.Image
	switch format {
	case "png":
		im, err = png.Decode(bytes.NewReader(data))
	case "jpeg":
		im, err = jpeg.Decode(bytes.NewReader(data))
	case "gif":
		im, err = gif.Decode(bytes.NewReader(data))
	case "webp":
		im, err = webp.Decode(bytes.NewReader(data))
	}
	if err != nil {
		return nil, refuse("decode", "image illisible ou corrompue")
	}
	out := &Image{}
	if format == "gif" {
		if g, e := gif.DecodeAll(bytes.NewReader(data)); e == nil && len(g.Image) > 1 {
			out.Note = "GIF animé : seule la première image est envoyée"
		}
	}
	b := im.Bounds()
	w, h := b.Dx(), b.Dy()
	if w > maxDim || h > maxDim {
		nw, nh := maxDim, maxDim*h/w
		if h > w {
			nw, nh = maxDim*w/h, maxDim
		}
		if nw < 1 {
			nw = 1
		}
		if nh < 1 {
			nh = 1
		}
		dst := image.NewNRGBA(image.Rect(0, 0, nw, nh))
		xdraw.CatmullRom.Scale(dst, dst.Bounds(), im, b, xdraw.Over, nil)
		im, w, h = dst, nw, nh
	}
	out.Width, out.Height = w, h
	var buf bytes.Buffer
	if format == "jpeg" {
		err = jpeg.Encode(&buf, im, &jpeg.Options{Quality: 85})
		out.Mime, out.Ext = "image/jpeg", "jpg"
	} else {
		err = (&png.Encoder{CompressionLevel: png.BestSpeed}).Encode(&buf, im)
		out.Mime, out.Ext = "image/png", "png"
		if err == nil && buf.Len() > maxOutBytes {
			buf.Reset()
			err = jpeg.Encode(&buf, flatten(im), &jpeg.Options{Quality: 85})
			out.Mime, out.Ext = "image/jpeg", "jpg"
		}
	}
	if err != nil {
		return nil, refuse("decode", "ré-encodage impossible")
	}
	out.Data = buf.Bytes()
	return out, nil
}

// flatten composites transparency over white (JPEG has no alpha).
func flatten(im image.Image) image.Image {
	dst := image.NewRGBA(im.Bounds())
	xdraw.Draw(dst, dst.Bounds(), image.NewUniform(color.White), image.Point{}, xdraw.Src)
	xdraw.Draw(dst, dst.Bounds(), im, im.Bounds().Min, xdraw.Over)
	return dst
}

// Limiter caps the number of images sent per sliding hour, all channels together.
type Limiter struct {
	mu     sync.Mutex
	max    int
	window time.Duration
	hits   []time.Time
	Now    func() time.Time // test clock (nil = time.Now)
}

func NewLimiter(perHour int) *Limiter {
	if perHour <= 0 {
		perHour = DefaultPerHour
	}
	return &Limiter{max: perHour, window: time.Hour}
}

// Allow consumes one slot, or returns a rate refusal.
func (l *Limiter) Allow() error {
	l.mu.Lock()
	defer l.mu.Unlock()
	now := time.Now()
	if l.Now != nil {
		now = l.Now()
	}
	keep := l.hits[:0]
	for _, t := range l.hits {
		if now.Sub(t) < l.window {
			keep = append(keep, t)
		}
	}
	l.hits = keep
	if len(l.hits) >= l.max {
		return refuse("rate", "limite atteinte : %d images par heure au maximum, réessaie plus tard", l.max)
	}
	l.hits = append(l.hits, now)
	return nil
}

// Guard bundles the policy and the rate limit shared by every sending path.
type Guard struct {
	Policy  *Policy
	Limiter *Limiter
}

// NewGuard builds a guard with the default limit.
func NewGuard(p *Policy) *Guard { return &Guard{Policy: p, Limiter: NewLimiter(DefaultPerHour)} }

// Vet checks the path and the rate limit and returns the image to send.
func (g *Guard) Vet(path string) (*Image, error) {
	if g == nil || g.Policy == nil {
		return nil, errors.New("envoi d'images non configuré")
	}
	img, err := g.Policy.Prepare(path)
	if err != nil {
		return nil, err
	}
	if err := g.Limiter.Allow(); err != nil {
		return nil, err
	}
	return img, nil
}

// CleanCaption keeps a short single-purpose caption: no control characters,
// at most 200 runes.
func CleanCaption(c string) string {
	c = strings.Map(func(r rune) rune {
		if r == '\n' || r == '\t' {
			return ' '
		}
		if r < 0x20 || r == 0x7f {
			return -1
		}
		return r
	}, c)
	c = strings.Join(strings.Fields(c), " ")
	if r := []rune(c); len(r) > 200 {
		c = string(r[:200]) + "…"
	}
	return c
}
